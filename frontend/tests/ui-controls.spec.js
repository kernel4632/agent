/* 自有控件回归：以用户键盘、输入、焦点与剪贴板结果验收迁移，不依赖组件内部 DOM。 */
import { expect, test } from '@playwright/test'
import { backend, navigate } from './chat-fixture.js'

test('select keyboard chooses a color and Escape keeps settings open', async ({ page }) => {
  await backend(page)
  await page.goto('/')
  await navigate(page, '设置')
  await page.getByRole('button', { name: /通用/ }).click()
  const select = page.getByRole('combobox', { name: '强调色' })
  await select.focus()
  await page.keyboard.press('Enter')
  await page.keyboard.press('End')
  await page.keyboard.press('Enter')
  await expect(select).toContainText('丁香')
  await expect(select).toBeFocused()
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('agent.appearance') || '{}').color)).toBe('#bba5d6')
  await page.keyboard.press('Enter')
  await page.keyboard.press('Escape')
  await expect(select).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('heading', { name: '通用', level: 1 })).toBeVisible()
})

test('modal traps Tab, returns focus, and receives the document theme', async ({ page }) => {
  await backend(page)
  await page.goto('/')
  await navigate(page, '新建对话')
  const trigger = page.getByRole('button', { name: '选择模型（当前 test-model）' })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: '选择模型', exact: true })
  await expect(dialog).toBeVisible()
  for (let index = 0; index < 12; index++) {
    await page.keyboard.press('Tab')
    expect(await dialog.evaluate(element => element.contains(document.activeElement))).toBe(true)
  }
  const colors = await dialog.evaluate(element => [getComputedStyle(element).getPropertyValue('--la-text').trim(), getComputedStyle(document.documentElement).getPropertyValue('--la-text').trim()])
  expect(colors[0]).toBeTruthy()
  expect(colors[0]).toBe(colors[1])
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
})

test('password visibility and invalid JSON draft survive until a complete object', async ({ page }) => {
  const mock = await backend(page)
  await page.goto('/')
  await navigate(page, '设置')
  await page.getByRole('button', { name: /模型供应商/ }).click()
  await page.getByRole('button', { name: /Test Provider/ }).click()
  const password = page.getByLabel('API Key', { exact: true })
  await expect(password).toHaveAttribute('type', 'password')
  await page.getByRole('button', { name: '显示密码' }).click()
  await expect(password).toHaveAttribute('type', 'text')
  await page.getByRole('button', { name: '隐藏密码' }).click()
  await expect(password).toHaveAttribute('type', 'password')
  await page.getByRole('tab', { name: '高级设置' }).click()
  const headers = page.getByRole('textbox', { name: '自定义请求头' })
  await headers.fill('{"X-Test":')
  await expect(page.getByRole('alert')).toContainText('JSON 尚未完整')
  await page.getByRole('textbox', { name: '额外请求体' }).focus()
  await expect(headers).toHaveValue('{"X-Test":')
  expect(mock.config().providers[0].headers).toEqual({ 'x-preserve': 'yes' })
  await headers.fill('{"X-Test":"ok"}')
  await expect.poll(() => mock.config().providers[0].headers).toEqual({ 'X-Test': 'ok' })
  expect(mock.errors).toEqual([])
})

test('attachment removal and code copying work without a component library', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  const mock = await backend(page)
  await page.goto('/')
  await navigate(page, '新建对话')
  await page.locator('input[type=file]').setInputFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('notes') })
  await page.getByRole('button', { name: '移除附件', exact: true }).click()
  await expect(page.locator('.chat-composer__file')).toHaveCount(0)
  await page.getByRole('textbox', { name: '消息', exact: true }).fill('keep running')
  await page.getByRole('button', { name: '发送消息', exact: true }).click()
  await expect(page.getByRole('button', { name: '停止生成', exact: true })).toBeVisible()
  await mock.emit('session-1', [{ type: 'agent-start' }, { type: 'text-delta', text: '```js\nconst answer = 42\n```' }])
  await page.getByRole('button', { name: '复制代码' }).click()
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe('const answer = 42')
  expect(mock.errors).toEqual([])
})
